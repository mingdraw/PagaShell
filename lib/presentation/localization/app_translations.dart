  /// Rust 桥接错误携带动态地址/句柄；只识别已知前缀，其他诊断保持原文。
  static String error(String message) {
    final rdp = RegExp(
      r'^(RDP NLA 认证失败|RDP 会话初始化失败)：([^（）\r\n]+)（([^（）\r\n]+)）$',
    ).firstMatch(message);
    if (rdp != null) {
      return '@stage：@reason（@code）'.trParams({
        'stage': rdp[1]!.tr,
        'reason': rdp[2]!.tr,
        'code': rdp[3]!,
      });
    }
    final bind = RegExp(r'^无法监听本地端口 (\d+)，请检查端口占用或权限$').firstMatch(message);
    if (bind != null) {
      return '无法监听本地端口 @port，请检查端口占用或权限'.trParams({'port': bind[1]!});
    }
    final forward = RegExp(r'^本地端口 (\d+) 的目标连接失败，请检查服务端口和转发权限$')
        .firstMatch(message);
    if (forward != null) {
      return '本地端口 @port 的目标连接失败，请检查服务端口和转发权限'.trParams({'port': forward[1]!});
    }
    for (final prefix in _errorPrefixes) {
      if (message.startsWith(prefix)) {
        return '$prefix@value'.trParams({
          'value': error(message.substring(prefix.length)),
        });
      }
    }
    return message.tr;
  }

